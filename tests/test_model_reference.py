def test_aliases_join_vendor_names_but_preserve_configuration_and_snapshots():
    a=model_identity('anthropic/claude-opus-5.5')
    b=model_identity('Claude-Opus-5.5')
    assert a['id']==b['id'] and a['name']==b['name']=='Claude Opus 5.5'
    assert a['release_date']=='2026-09-22'
    assert model_identity('Claude Haiku 4.5')['id']==model_identity('anthropic/claude-haiku-4.5')['id']
    assert model_identity('GPT-5.5 high')['variant']=='high'
    assert model_identity('GPT-5.5')['id'] != model_identity('GPT-5.6-Sol')['id']
    assert model_identity('unlisted-new-model')['release_date'] is None
    assert model_identity('Qwen3.6-27B-PRISM-PRO-DQ-agent')['id'] != model_identity('Qwen3.6-27B-PRISM-PRO-DQ-code')['id']

def test_sparse_tasks_stay_archived_and_common_catalog_has_real_sources():
    c=list_showcase()
    assert sum(t['default_visible'] for t in c['tasks'])==42
    assert all(t['default_visible']==(t['model_count']>=6) for t in c['tasks'])
    assert all(not t['default_visible'] for t in c['tasks'] if t['id'] in {'analog-clock-html','rotating-hexagon-html'})
    assert len(reference()['models'])>=600
    assert sum(len(m.get('benchmarks',[])) for m in reference()['models'])>=1000

