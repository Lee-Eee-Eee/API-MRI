def test_grid_chooses_exact_model_and_effort():
    svg='<svg xmlns="http://www.w3.org/2000/svg"><text>high</text></svg>'
    encoded=base64.b64encode(svg.encode()).decode()
    page=f'<img alt="Pelican riding a bicycle, generated by gpt-6.1-terra at high reasoning effort" src="data:image/svg+xml;base64,{encoded}">'
    example={'model':'GPT-6.1 Terra','reported_settings':{'reasoning_effort':'high'}}
    assert grid_svg(page,example)==svg
    with pytest.raises(ValueError):grid_svg(page,example|{'reported_settings':{'reasoning_effort':'xhigh'}})
    with pytest.raises(ValueError):grid_svg(page,example|{'model':'GPT-6.1 Sol'})

def test_remote_html_keeps_an_opaque_network_free_boundary(tmp_path,monkeypatch):
    from relay_audit import showcase_preview
    html='<html><script type="module">import * as THREE from "three";</script></html>'
    monkeypatch.setattr(showcase_preview,'_download',lambda url:html.encode())
    entry=next(e for e in list_showcase()['examples'] if e['task_id']=='design-jupiter')
    with TestClient(create_app(tmp_path),base_url='http://127.0.0.1:8765') as client:
        r=client.get('/api/showcase/examples/'+entry['id']+'/preview')
        assert r.status_code==200 and 'data:text/javascript;base64,' in r.text
        csp=r.headers['content-security-policy']
        assert 'sandbox allow-scripts;' in csp and 'allow-same-origin' not in csp
        assert "connect-src 'none'" in csp and 'https:' not in csp
        assert client.get('/api/showcase/examples/unknown/original').status_code==404
        data=client.get('/api/capability-reference').json()
        assert {'bfcl','swe','aa','livebench','terminal','arena'}=={b['id'] for b in data['benchmarks']}

def test_runtime_modules_keep_upstream_hashes():
    folder=Path(__file__).parents[1]/'src/relay_audit/data/showcase/runtime'
    import hashlib
    for entry in json.loads((folder/'NOTICE.json').read_text('utf8'))['files']:
        assert hashlib.sha256((folder/entry['file']).read_bytes()).hexdigest()==entry['sha256']
