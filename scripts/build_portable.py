def _copy_notices(bundle: Path) -> list[dict]:
    """Preserve wheel license trees and identify the exact build environment."""
    notices = bundle / "licenses"
    notices.mkdir()
    packages = []
    for dist in sorted(metadata.distributions(), key=lambda d: d.metadata["Name"].lower()):
        name = dist.metadata["Name"]
        safe = re.sub(r"[^A-Za-z0-9_.+-]", "_", f"{name}-{dist.version}")
        files = []
        for entry in dist.files or ():
            relative = Path(str(entry))
            # Wheel RECORD paths can escape site-packages for console scripts.
            # Select license files only; never copy arbitrary installed data.
            if any(part == ".." for part in relative.parts):
                continue
            if not any(re.search(r"license|licence|copying|copyright|notice", part, re.I)
                       for part in relative.parts):
                continue
            source = Path(dist.locate_file(entry))
            if not source.is_file() or source.is_symlink():
                continue
            target = notices / safe / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            files.append(target.relative_to(bundle).as_posix())
        urls = dist.metadata.get_all("Project-URL", [])
        packages.append({"name": name, "version": dist.version,
                         "license_expression": dist.metadata.get("License-Expression"),
                         "home_page": dist.metadata.get("Home-page"),
                         "project_urls": urls, "license_files": files})
    base = Path(sys.base_prefix)
    python_license = next((p for p in (base / "LICENSE.txt", base / "LICENSE") if p.is_file()), None)
    if python_license is None:
        raise RuntimeError("CPython LICENSE.txt was not found; do not publish without it")
    shutil.copy2(python_license, notices / "CPython-LICENSE.txt")
    # Tcl/Tk wheels/runtime layouts vary; both standard Tcl directories and
    # PyInstaller's collected data are checked, preserving existing license text.
    tcl_files = []
    for start in (base / "tcl", bundle / "_internal" / "_tcl_data",
                  bundle / "_internal" / "_tk_data"):
        if start.is_dir():
            for path in start.rglob("*"):
                if path.is_file() and re.search(r"license|licence|copying", path.name, re.I):
                    target = notices / "Tcl-Tk" / start.name / path.relative_to(start)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(path, target)
                    tcl_files.append(target.relative_to(bundle).as_posix())
    if not tcl_files:
        raise RuntimeError("Tcl/Tk license files were not found; do not publish without them")
    (notices / "README.txt").write_text(
        "License texts are copied unchanged from the installed distributions.\n"
        "build-manifest.json identifies versions and upstream project URLs.\n"
        "certifi and tqdm Python sources are retained under _internal.\n"
        "The bundle uses the CPU build of PyTorch; no model weights are included.\n",
        encoding="utf-8")
    return packages


def _source_revision() -> str | None:
    run = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return run.stdout.strip() if run.returncode == 0 else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True,
                        help="New output directory; existing paths are refused")
    parser.add_argument("--no-zip", action="store_true", help="Leave an unpacked bundle for testing")
    args = parser.parse_args(argv)
    if sys.platform != "win32" or platform.machine().lower() not in {"amd64", "x86_64"}:
        parser.error("Build on Windows x64 with a 64-bit Python interpreter")
    if struct.calcsize("P") != 8:
        parser.error("A 64-bit Python interpreter is required")
    out = args.out.resolve()
    if out.exists():
        parser.error("Output already exists; choose a new directory to preserve previous builds")
    # Verify the CPU wheel before creating any output.
    import torch
    if torch.version.cuda is not None or "+cpu" not in torch.__version__:
        parser.error("Install the CPU-only PyTorch wheel before building")
    if metadata.version("pyinstaller") != "6.22.3":
        parser.error("Install scripts/requirements-build.txt first (PyInstaller 6.22.3)")
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    version = project["project"]["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        parser.error("Portable release version must be MAJOR.MINOR.PATCH")
    folder = f"API-MRI-{version}-windows-x64"
    out.mkdir(parents=True)
    work = out / "work"
    work.mkdir()
    (work / "portable_window_entry.py").write_text(
        "from multiprocessing import freeze_support\n"
        "if __name__ == '__main__':\n"
        "    freeze_support()\n"
        "    from relay_audit.portable import main\n"
        "    raise SystemExit(main())\n", encoding="utf-8")
    (work / "portable_cli_entry.py").write_text(
        "from multiprocessing import freeze_support\n"
        "if __name__ == '__main__':\n"
        "    freeze_support()\n"
        "    from relay_audit.cli import main\n"
        "    raise SystemExit(main())\n", encoding="utf-8")
    _write_icon(work / "api-mri.ico")
    (work / "version_info.txt").write_text(_version_info(version), encoding="utf-8")
    spec = work / "API-MRI.spec"
    spec.write_text(_spec(work, folder), encoding="utf-8")
    subprocess.run([sys.executable, "-X", "utf8", "-m", "PyInstaller", "--noconfirm",
                    "--distpath", str(out / "dist"), "--workpath", str(work / "pyinstaller"),
                    str(spec)], cwd=ROOT, check=True)
    bundle = out / "dist" / folder
    # Editable-install direct_url metadata contains the builder's path. It is
    # not needed by the runtime and must not enter a distributed artifact.
    for path in bundle.rglob("direct_url.json"):
        if path.is_file():
            path.unlink()
    for name in ("LICENSE", "THIRD_PARTY.md"):
        shutil.copy2(ROOT / name, bundle / name)
    (bundle / "README.md").write_text(
        f"# API-MRI {version}\n\n"
        "双击 **API-MRI.exe** 打开工作台。关闭启动窗口即可退出。\n\n"
        "检测记录与参考库保存在同目录的 `data/`；移动软件时保留整个文件夹。\n\n"
        "首次使用见 [使用说明](使用说明.md)。\n\n"
        f"[源代码与完整指南]({REPOSITORY}) · [版本下载]({REPOSITORY}/releases)\n",
        encoding="utf-8")
    for pattern in ("docs/*.md", "docs/*.json", "docs/images/*.jpg", "docs/images/*.png",
                    "examples/*.json"):
        for source in ROOT.glob(pattern):
            if source.is_file() and not source.is_symlink():
                target = bundle / source.relative_to(ROOT)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
    if (ROOT / "docs" / "portable.md").is_file():
        shutil.copy2(ROOT / "docs" / "portable.md", bundle / "使用说明.md")
    packages = _copy_notices(bundle)
    # Every distributed byte is accounted for, before generating the manifest.
    files = {str(path.relative_to(bundle)).replace("\\", "/"): {
        "size": path.stat().st_size, "sha256": digest(path)}
        for path in sorted(bundle.rglob("*")) if path.is_file()}
    manifest = {"schema": 1, "name": "API-MRI", "version": version,
                "platform": "windows-x64", "python": platform.python_version(),
                "pyinstaller": metadata.version("pyinstaller"),
                "built_at_utc": datetime.now(timezone.utc).isoformat(),
                "source_repository": REPOSITORY, "source_revision": _source_revision(),
                "dependency_inventory_scope": "installed build environment; licenses may include unused transitive packages",
                "packages": packages, "files": files,
                "model_weights_included": False, "user_data_included": False}
    (bundle / "build-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if not args.no_zip:
        archive = out / f"{folder}.zip"
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zipped:
            for path in sorted(bundle.rglob("*")):
                if path.is_file():
                    zipped.write(path, path.relative_to(bundle.parent).as_posix())
        with zipfile.ZipFile(archive) as zipped:
            bad = zipped.testzip()
            if bad:
                raise RuntimeError(f"Archive integrity check failed: {bad}")
        checksum = digest(archive)
        (out / "SHA256SUMS.txt").write_text(f"{checksum}  {archive.name}\n", encoding="ascii")
        print(json.dumps({"archive": str(archive), "bytes": archive.stat().st_size,
                          "sha256": checksum, "files": len(files) + 1}))
    else:
        print(json.dumps({"bundle": str(bundle), "files": len(files) + 1}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
