"""Build the complete Windows x64 portable workbench in a fresh directory.

Run with the project environment's Python. Runtime dependencies must already be
installed; this script never installs packages, fetches model weights or reads
user runs. The archive contains two executables sharing one _internal folder.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
from importlib import metadata
import json
import os
from pathlib import Path
import platform
import re
import shutil
import struct
import subprocess
import sys
import tomllib
import zipfile


ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "https://github.com/Lee-Eee-Eee/API-MRI"


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def _write_icon(path: Path) -> None:
    """Native 48px BGRA icon using the workbench's existing three bars."""
    size = 48
    colors = [(203, 163, 126), (183, 128, 95), (238, 233, 216)]
    pixels = bytearray()
    for y in reversed(range(size)):
        for x in range(size):
            rgb = (39, 46, 41)
            alpha = 255
            # Rounded corners, matching the existing browser favicon.
            if (x < 5 or x > 42) and (y < 5 or y > 42):
                cx, cy = (6 if x < 24 else 41), (6 if y < 24 else 41)
                if (x - cx) ** 2 + (y - cy) ** 2 > 42:
                    alpha = 0
            for (left, top), color in zip(((8, 17), (20, 24), (32, 7)), colors):
                if left <= x < left + 8 and top <= y < 41:
                    rgb = color
            pixels.extend((*reversed(rgb), alpha))
    mask = bytes(((size + 31) // 32) * 4 * size)
    bitmap = struct.pack("<IIIHHIIIIII", 40, size, size * 2, 1, 32, 0,
                         len(pixels) + len(mask), 0, 0, 0, 0) + pixels + mask
    path.write_bytes(struct.pack("<HHH", 0, 1, 1) + struct.pack(
        "<BBBBHHII", size, size, 0, 0, 1, 32, len(bitmap), 22) + bitmap)


def _version_info(version: str) -> str:
    numbers = tuple(int(v) for v in version.split(".")[:3]) + (0,)
    return f'''VSVersionInfo(
  ffi=FixedFileInfo(filevers={numbers!r}, prodvers={numbers!r}, mask=0x3f,
      flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('CompanyName', 'API-MRI contributors'),
    StringStruct('FileDescription', 'API-MRI'),
    StringStruct('FileVersion', {version!r}),
    StringStruct('ProductName', 'API-MRI'),
    StringStruct('ProductVersion', {version!r}),
    StringStruct('LegalCopyright', 'MIT; third-party licenses included')
  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])])
'''


