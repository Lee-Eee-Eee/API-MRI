import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const folder = path.dirname(fileURLToPath(import.meta.url));
export async function build({ outDir = path.join(folder, 'lib') } = {}) {
  const core = await readFile(path.join(folder, 'src/core.js'), 'utf8');
  const client = await readFile(path.join(folder, 'src/client.js'), 'utf8');
  const host = await readFile(path.join(folder, 'src/index.js'), 'utf8');
  const body = `${core}\n${client}`
    .replace(/^import React from 'react';\r?\n/m, '')
    .replace(/^import \{[\s\S]*?\} from '\.\/core\.js';\r?\n/m, '')
    .replace(/^export /gm, '');
  const browser = `// Generated by dsh-plugin/build.mjs. Edit src/, then run npm run build:dsh.\n` +
    `window.__ModuleLoader__.load({\n  id: 'dsh-api-mri',\n  factory: (require) => {\n` +
    `    const React = require('react');\n${body}\n` +
    `    return { name, inject, apply };\n  }\n});\n`;
  new vm.Script(browser, { filename: 'dsh-api-mri/client.js' });
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, 'client.js'), browser);
  await writeFile(path.join(outDir, 'index.js'), host);
  return { browser, host };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build();
  console.log('Built dsh-api-mri host and browser entries.');
}
