"""Read a catalog-pinned public original into an isolated, network-free preview.

Public originals are kept in bounded process memory, not repackaged as assets.
The caller accepts only catalog IDs; it cannot supply a URL or request headers.
"""
from __future__ import annotations
from functools import lru_cache
import base64
import hashlib
import re
from pathlib import Path
from urllib.parse import urlsplit
import httpx
from html.parser import HTMLParser

ROOT = Path(__file__).parent/'data/showcase'
REPOS = {'vastxie/pelican-gallery-data', 'diegocp01/html_ai_battle', 'jdmnk/design-benchmark'}
GRIDS = {'https://static.simonwillison.net/static/2026/openai-pelicans-october-2026.html',
         'https://static.simonwillison.net/static/2026/claude-pelicans-grid.html'}
MAX_BYTES = 2 * 1024 * 1024

def original_url(example: dict) -> str | None:
    value = example.get('remote_preview_url') or example.get('artifact_url') or example.get('source', {}).get('url', '')
    parsed = urlsplit(value)
    if parsed.scheme != 'https' or parsed.username or parsed.password or parsed.port or parsed.query or parsed.fragment:
        return None
    if value in GRIDS and example.get('reported_outcome') != 'no_svg_returned':
        return value
    if parsed.hostname == 'gally.net' and re.fullmatch(r'/temp/20251107pelican-alternatives/svgs/[\w.-]+\.svg', parsed.path):
        return value
    match = re.fullmatch(r'/([^/]+/[^/]+)/blob/([a-f0-9]{40})/([\w./-]+\.(?:html|svg))', parsed.path)
    if parsed.hostname == 'github.com' and match and match[1] in REPOS and '..' not in match[3].split('/'):
        return 'https://raw.githubusercontent.com/'+'/'.join(match.groups())
    return None

@lru_cache(maxsize=16)
def _download(url: str) -> bytes:
    # Respect the user's HTTPS proxy / CA configuration for public originals.
    # Redirects, cookies and application credentials are not forwarded.
    with httpx.Client(timeout=httpx.Timeout(20, connect=8), follow_redirects=False, trust_env=True) as client:
        with client.stream('GET', url, headers={'User-Agent': 'API-MRI-public-preview/0.9'}) as response:
            response.raise_for_status()
            if response.status_code != 200:
                raise ValueError('原站未返回作品。')
            chunks, length = [], 0
            for chunk in response.iter_bytes():
                length += len(chunk)
                if length > MAX_BYTES:
                    raise ValueError('原作超过预览大小限制。')
                chunks.append(chunk)
            return b''.join(chunks)

def read_original(example: dict) -> str:
    url = original_url(example)
    if not url:
        raise ValueError('这份记录没有独立的公开作品文件。')
    raw = _download(url)
    if url in GRIDS:
        return grid_svg(raw.decode('utf-8'), example)
    digest = example.get('reported_artifact_sha256')
    if digest and hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError('原作与作者记录的哈希不一致。')
    return raw.decode('utf-8-sig')

class _Grid(HTMLParser):
    def __init__(self):
        super().__init__(); self.images=[]
    def handle_starttag(self, tag, attrs):
        values=dict(attrs)
        if tag=='img' and values.get('src','').startswith('data:image/svg+xml;base64,'):
            self.images.append(values)

def grid_svg(source: str, example: dict) -> str:
    from .model_reference import model_identity, name_key
    model=model_identity(example.get('model',''))
    identifier=model['id'].split('/')[-1]
    effort=example.get('reported_settings',{}).get('reasoning_effort')
    parser=_Grid();parser.feed(source)
    candidates=[]
    for image in parser.images:
        alt=image.get('alt','')
        # Match the entire model token and the entire effort token; high must
        # not select xhigh, Opus 5 must not select Opus 5.5.
        exact_openai=re.search(r'generated by ([\w.-]+) at (\w+) reasoning effort',alt,re.I)
        exact_claude=re.fullmatch(r'(.+), thinking effort (\w+)',alt,re.I)
        if exact_openai:
            selected=exact_openai[1].lower()==identifier.lower() and exact_openai[2]==effort
        elif exact_claude:
            selected=name_key(exact_claude[1])==name_key(model['name']) and exact_claude[2]==effort
        else: selected=False
        if selected:candidates.append(image['src'])
    if len(candidates)!=1:raise ValueError('未找到唯一对应的模型与推理档位。')
    return base64.b64decode(candidates[0].split(',',1)[1],validate=True).decode('utf-8')

@lru_cache(maxsize=1)
def _importmap() -> str:
    import json
    imports = {}
    for name, file in [('three', 'three.module.js'), ('three/addons/controls/OrbitControls.js', 'OrbitControls.js')]:
        path = ROOT/'runtime'/file
        if path.is_file():
            imports[name] = 'data:text/javascript;base64,'+base64.b64encode(path.read_bytes()).decode('ascii')
    return '<script type="importmap">'+json.dumps({'imports': imports})+'</script>' if imports else ''

def prepare_html(source: str) -> str:
    # Only the benchmark with a declared three.js r160 import map needs this
    # replacement. Other HTML keeps its original bytes and the network stays off.
    if re.search(r'''(?:from\s*|import\s*)['"]three(?:/addons/controls/OrbitControls\.js)?['"]''', source):
        source = re.sub(r'<script\b[^>]*type=[\'"]importmap[\'"][^>]*>.*?</script\s*>', '', source, flags=re.I | re.S)
        source = _importmap()+source
    return source
